def _real_response(**overrides) -> dict:
    """Run the REAL PrioritizationResource against the stub data sources and
    return its emitted prioritize_risk_signals response (generatedAt stripped for
    byte-stability — it is optional in the strict contract and the gate never reads
    it)."""
    resource = PrioritizationResource(
        api_key="fake",
        chemical_resource=StubChemicalResource(),
        bioactivity_resource=overrides.get("bioactivity", StubBioactivityResource()),
        exposure_resource=overrides.get("exposure", StubExposureResource()),
    )
    res = resource.execute_tool("prioritize_risk_signals", {"dtxsid": "DTXSID7020182"})
    res.get("provenanceSummary", {}).pop("generatedAt", None)
    return res


def _bridge_codes(packet: dict) -> set[str]:
    """source-contract + project + run the REAL engine; collect blocking codes."""
    cf = source_contract.validate_source_packet(packet, corpus="test")
    if cf is not None:
        return {cf.code}
    codes: set[str] = set()
    for obj in projector.project_packet(packet):
        result = bridge.validate_object(obj)
        codes |= set(result.blocking_codes)
    return codes


