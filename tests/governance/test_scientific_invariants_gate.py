"""Adversarial self-tests for the comptox-mcp Track-B scientific-invariants gate.

The gated released object is the SERVER-AUTHORED ``prioritize_risk_signals``
conclusion (a ``BioactivityExposureRatioRecord`` in spine terms). These tests
prove, through the REAL vendored spine engine (no stubbing of the bridge):

1. PRISTINE — the real producer's emitted response passes the strict emission
   contract AND the spine engine (no blocking code).
2. PER-CODE BITE — each ADVERTISED code (BER_NOT_RISK_OR_REGULATORY,
   BER_UNCERTAINTY_AND_CEILING_REQUIRED) bites on a producer-emittable,
   emission-schema-VALID fault, generated by mutating the REAL producer's authored
   conclusion the way a producer regression would.
3. GUARD REJECTS A FORBIDDEN FIELD — an undeclared field at a strict emission level
   is a SOURCE_CONTRACT_VIOLATION that BLOCKS before any projection (closes the
   dead-arm class).
4. NEGATION SAFETY — an honest "not a regulatory risk determination" disclaimer is
   NOT mistaken for a risk/regulatory authorization.
5. HONEST-DROP — the inconclusive band maps faithfully to a passing comparable
   class (BER_REQUIRES_COMPARABILITY is not falsely RED-ed on a pristine
   inconclusive packet).
6. FAIL-CLOSED — an unrecognized projected schemaId blocks rather than sailing
   through as the engine's silent valid:true no-op.
7. DETERMINISM — the projection is byte-stable.
"""

